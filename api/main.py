# REQUEST/RESPONSE MODELS
# ============================================================
class EmailScanRequest(BaseModel):
    email_content: str = Field(..., min_length=1, max_length=5000)
    sender: Optional[str] = None
    subject: Optional[str] = None


class ScanResponse(BaseModel):
    risk_score: float
    is_phishing: bool
    confidence: float
    action: str
    model_version: str
    timestamp: str
    alert_sent: bool = False


# ============================================================
# PHISHING KEYWORDS FOR FALLBACK DETECTION
# ============================================================
PHISHING_KEYWORDS = [
    'verify', 'click here', 'urgent', 'compromised', 'suspended',
    'unusual login', 'congratulations', 'invoice', 'past due',
    'expire', 'payment', 'limited', 'blocked', 'password reset',
    'account verification', 'security alert', 'immediate action'
]


def get_matched_patterns(email_content: str) -> List[str]:
    """Return list of phishing patterns found in email"""
    email_lower = email_content.lower()
    return [p for p in PHISHING_KEYWORDS if p in email_lower]


# ============================================================
# SCAN ENDPOINT
# ============================================================
@app.post("/scan", response_model=ScanResponse)
async def scan_email(request: EmailScanRequest, background_tasks: BackgroundTasks):
    """
    AI-powered scan with automatic enforcement (DevSecOps gate)
    Sends email alerts for high-risk detections
    """
    logger.info(f"📧 Scanning email from: {request.sender or 'unknown'}")

    # Get matched patterns for alert
    matched_patterns = get_matched_patterns(request.email_content)

    if model is None or vectorizer is None:
        # Fallback rule-based detection
        email_lower = request.email_content.lower()
        risk_score = sum(0.12 for p in PHISHING_KEYWORDS if p in email_lower)
        risk_score = min(risk_score, 1.0)
        logger.info("Using fallback rule-based detection")
    else:
        # ML-based detection
        email_vector = vectorizer.transform([request.email_content])
        proba = model.predict_proba(email_vector)[0]
        risk_score = float(proba[1])

    confidence = abs(risk_score - 0.5) * 2

    # DevSecOps: Enforce Security Policy
    if risk_score > 0.75:
        action = "BLOCK"
        logger.warning(f"🚨 BLOCKED: High-risk email (score: {risk_score:.2%})")
        background_tasks.add_task(log_incident, request.email_content, risk_score, action)

        # Send email alert for high-risk detections
        background_tasks.add_task(
            send_phishing_alert,
            email_content=request.email_content,
            risk_score=risk_score,
            action=action,
            sender=request.sender,
            subject=request.subject,
            matched_patterns=matched_patterns
        )
        alert_sent = True

    elif risk_score > 0.5:
        action = "QUARANTINE"
        logger.warning(f"⚠️ QUARANTINED: Suspicious email (score: {risk_score:.2%})")
        background_tasks.add_task(log_incident, request.email_content, risk_score, action)

        # Send alert for quarantine as well (medium-high risk)
        if risk_score > 0.65:
            background_tasks.add_task(
                send_phishing_alert,
                email_content=request.email_content,
                risk_score=risk_score,
                action=action,
                sender=request.sender,
                subject=request.subject,
                matched_patterns=matched_patterns
            )
            alert_sent = True
        else:
            alert_sent = False

    else:
        action = "ALLOW"
        logger.info(f"✅ ALLOWED: Safe email (score: {risk_score:.2%})")
        alert_sent = False

    return ScanResponse(
        risk_score=risk_score,
        is_phishing=risk_score > 0.5,
        confidence=confidence,
        action=action,
        model_version=model_metadata.get('model_version', '1.0.0'),
        timestamp=datetime.utcnow().isoformat(),
        alert_sent=alert_sent
    )


