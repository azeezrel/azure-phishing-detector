# ============================================================
# EMAIL ALERT FUNCTION
# ============================================================
def send_phishing_alert(
    email_content: str,
    risk_score: float,
    action: str,
    sender: str = None,
    subject: str = None,
    matched_patterns: List[str] = None
) -> bool:
    """
    Send an email alert when phishing is detected
    """
    # Get configuration from environment variables
    smtp_server = os.getenv("SMTP_SERVER", "")
    smtp_port = int(os.getenv("SMTP_PORT", 587))
    smtp_username = os.getenv("SMTP_USERNAME", "")
    smtp_password = os.getenv("SMTP_PASSWORD", "")
    alert_recipients = os.getenv("ALERT_RECIPIENTS", "").split(",")

    if not smtp_username or not smtp_password:
        logger.warning("Email credentials not configured. Skipping alert.")
        return False

    if not alert_recipients or alert_recipients == ['']:
        logger.warning("No alert recipients configured. Skipping alert.")
        return False

    # Only send alerts for high-risk emails
    if risk_score < 0.7:
        logger.info(f"Risk score {risk_score:.2%} below threshold. No alert sent.")
        return False

    severity = "🔴 CRITICAL" if risk_score > 0.85 else "🟠 HIGH"

    # HTML email body
    html_body = f"""
    <html>
    <head>
        <style>
            body {{ font-family: Arial, sans-serif; }}
            .header {{ background-color: #c62828; color: white; padding: 15px; border-radius: 5px; }}
            .risk-high {{ color: #c62828; font-weight: bold; font-size: 18px; }}
            .info {{ background-color: #f5f5f5; padding: 10px; margin: 10px 0; border-radius: 5px; }}
            .details {{ font-family: monospace; white-space: pre-wrap; background-color: #fafafa; padding: 10px; }}
        </style>
    </head>
    <body>
        <div class="header">
            <h2>{severity} Phishing Threat Detected!</h2>
        </div>

        <div class="info">
            <p><strong>🛡️ Confidence Score:</strong> <span class="risk-high">{risk_score:.1%}</span></p>
            <p><strong>🚨 Action Taken:</strong> {action}</p>
            <p><strong>📅 Detection Time:</strong> {datetime.now().strftime('%Y-%m-%d %H:%M:%S UTC')}</p>
        </div>

        <div class="info">
            <h3>📧 Original Email Details:</h3>
            <p><strong>From:</strong> {sender or 'Unknown'}</p>
            <p><strong>Subject:</strong> {subject or 'No subject'}</p>
        </div>
    """

    if matched_patterns:
        html_body += f"""
        <div class="info">
            <h3>🎯 Detection Patterns:</h3>
            <ul>
                {"".join(f'<li>{pattern}</li>' for pattern in matched_patterns[:5])}
            </ul>
        </div>
        """

    html_body += f"""
        <div class="info">
            <h3>📝 Suspicious Email Content:</h3>
            <div class="details">{email_content[:500]}{'...' if len(email_content) > 500 else ''}</div>
        </div>

        <div class="info">
            <h3>⚠️ Recommended Actions:</h3>
            <ul>
                <li>Do NOT click any links in this email</li>
                <li>Do NOT reply or forward to others</li>
                <li>Block the sender domain in your email gateway</li>
                <li>Investigate if any credentials were recently shared</li>
            </ul>
        </div>

        <hr>
        <p><small>Generated by AI-Powered Phishing Detection System | MLOps + DevSecOps Pipeline</small></p>
    </body>
    </html>
    """

    plain_body = f"""
    {severity} PHISHING THREAT DETECTED!

    Confidence Score: {risk_score:.1%}
    Action Taken: {action}
    Detection Time: {datetime.now().strftime('%Y-%m-%d %H:%M:%S UTC')}

    Original Email:
    From: {sender or 'Unknown'}
    Subject: {subject or 'No subject'}

    Suspicious Content:
    {email_content[:500]}

    Recommended Actions:
    - Do NOT click any links in this email
    - Block the sender domain
    - Investigate for credential exposure

    ---
    AI-Powered Phishing Detection System
    """

    try:
        msg = MIMEMultipart('alternative')
        msg['From'] = smtp_username
        msg['To'] = ', '.join(alert_recipients)
        msg['Subject'] = f"[PHISHING ALERT] {severity} - {risk_score:.0%} confidence"

        msg.attach(MIMEText(plain_body, 'plain'))
        msg.attach(MIMEText(html_body, 'html'))

        with smtplib.SMTP(smtp_server, smtp_port) as server:
            server.starttls()
            server.login(smtp_username, smtp_password)
            server.sendmail(smtp_username, alert_recipients, msg.as_string())

        logger.info(f"✅ Phishing alert sent to {len(alert_recipients)} recipient(s)")
        return True

    except Exception as e:
        logger.error(f"❌ Failed to send email alert: {str(e)}")
        return False


